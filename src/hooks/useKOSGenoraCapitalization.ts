  id: string;
  spaceType: string;
  name: string;
  client: string;
  sector: string;
  jurisdiction: string;
  pastAnalyses: string[];
  decisions: string[];
  hypothesesRetained: string[];
  hypothesesRejected: string[];
  sources: string[];
  arbitrages: string[];
  documents: string[];
  experts: string[];
  reconstitutionDate: string;
  confidenceScore: number;
