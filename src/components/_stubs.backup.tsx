// ======================================================
// IMAGE LOADER
// ======================================================

export async function loadImg(
  src: string
): Promise<HTMLImageElement | null> {


  if (
    typeof window === "undefined" ||
    typeof Image === "undefined"
  ) {

    return null;

  }


  return new Promise((resolve)=>{


    const img = new Image();


    img.onload = () => {

      resolve(img);

    };


    img.onerror = () => {

      resolve(null);

    };


    img.src = src;


  });


}


